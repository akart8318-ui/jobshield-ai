// =====================================================
// CORE ENGINE
// =====================================================
let _currentLang = 'en';

/** Returns the string for a key in the active language. */
function t(key) {
  const entry = I18N_STRINGS[key];
  if (!entry) return key;
  return entry[_currentLang] || entry['en'] || key;
}

/** Applies translations to every [data-i18n] element on the page. */
function applyTranslations(lang) {
  _currentLang = lang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key  = el.getAttribute('data-i18n');
    const attr = el.getAttribute('data-i18n-attr'); // e.g. "placeholder"
    const val  = t(key);
    if (attr) {
      el.setAttribute(attr, val);
    } else {
      el.innerText = val;
    }
  });

  // Update <html lang> attribute
  document.documentElement.lang = lang === 'hi' ? 'hi' : 'en';

  // Update switcher button label & tooltip
  const btn = document.getElementById('langSwitchBtn');
  if (btn) {
    btn.innerHTML = lang === 'hi'
      ? '<span class="lang-flag">????</span><span class="lang-label">EN</span>'
      : '<span class="lang-flag">????</span><span class="lang-label">??????</span>';
    btn.title = lang === 'hi' ? 'Switch to English' : '?????? ??? ?????';
  }
}

/** Toggles between English and Hindi and persists the choice. */
function toggleLanguage() {
  const next = _currentLang === 'en' ? 'hi' : 'en';
  localStorage.setItem('jobshield_lang', next);
  applyTranslations(next);
}

/** Reads saved preference (or defaults to 'en') and applies it. */
function initLanguage() {
  const saved = localStorage.getItem('jobshield_lang') || 'en';
  applyTranslations(saved);
}
